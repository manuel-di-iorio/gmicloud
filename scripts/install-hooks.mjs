import { execFileSync } from 'node:child_process';
import { writeFileSync, chmodSync, mkdirSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();

let hooksDir;
try {
  hooksDir = execFileSync('git', ['rev-parse', '--git-path', 'hooks'], { cwd: root, encoding: 'utf8' }).trim();
} catch (e) {
  console.error('[install-hooks] not a git repository, skipping');
  process.exit(0);
}
if (!path.isAbsolute(hooksDir)) hooksDir = path.resolve(root, hooksDir);
mkdirSync(hooksDir, { recursive: true });

const hookPath = path.join(hooksDir, 'pre-commit');

const hook = `#!/bin/sh
# Auto-generated by scripts/install-hooks.mjs - do not edit by hand.
# Rebuilds the design-system CSS bundle before every commit and stages it
# so the committed assets/css/app.css never drifts from the SCSS sources.
set -e
npm run build:css
if ! git diff --quiet -- assets/css/app.css; then
  git add assets/css/app.css
fi
exit 0
`;

writeFileSync(hookPath, hook, 'utf8');
try { chmodSync(hookPath, 0o755); } catch { /* windows: chmod is a no-op-ish */ }
console.log(`[install-hooks] wrote ${hookPath}`);

export {};
