import { mkdirSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import tailwindcss from 'tailwindcss';
import autoprefixer from 'autoprefixer';
import * as sass from 'sass';

const root = process.cwd();
const watch = process.argv.includes('--watch');

async function buildOnce() {
  const twInput = path.join(root, 'assets/design-system/tailwind.css');
  const twCss = readFileSync(twInput, 'utf8');
  const twResult = await postcss([tailwindcss(path.join(root, 'tailwind.config.js')), autoprefixer()])
    .process(twCss, { from: twInput, to: undefined });
  const twOut = twResult.css;

  const scssEntry = path.join(root, 'assets/design-system/scss/app.scss');
  const dsResult = sass.compile(scssEntry, { style: 'expanded', loadPaths: [path.join(root, 'assets/design-system/scss')] });
  const dsOut = dsResult.css.toString();

  mkdirSync(path.join(root, 'assets/css'), { recursive: true });
  const out = `/* GMI Cloud design system bundle. Generated by npm run build:css — do not edit directly. */\n${twOut}\n${dsOut}\n`;
  writeFileSync(path.join(root, 'assets/css/app.css'), out);
  console.log(`[build:css] wrote assets/css/app.css (${out.length} bytes)`);
}

await buildOnce();

if (watch) {
  console.log('[build:css] watching assets/design-system…');
  const { watch: fsWatch } = await import('node:fs');
  const dirs = [path.join(root, 'assets/design-system'), path.join(root, 'tailwind.config.js')];
  let timer = null;
  const trigger = () => {
    clearTimeout(timer);
    timer = setTimeout(() => { buildOnce().catch((e) => console.error(e.message)); }, 250);
  };
  for (const d of dirs) {
    try {
      fsWatch(d, { recursive: true }, trigger);
    } catch (e) {
      console.error(`cannot watch ${d}: ${e.message}`);
    }
  }
  setInterval(() => {}, 10000);
}
